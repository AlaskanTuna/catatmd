const DEID_TOKEN_PATTERN = /\[[a-z]+_\d+\]|[a-z]+_\d+/gi
const NON_LETTERS = /[^a-z]+/g
const NON_ALPHA = /[^a-z]/g

export function buildLexicalQuery(text: string, limit = 12): string {
  const normalised = text.toLowerCase().replace(DEID_TOKEN_PATTERN, ' ')
  const tokens = normalised.split(NON_LETTERS)

  const counts = new Map<string, number>()
  for (const token of tokens) {
    if (token.length < 4) continue
    if (STOP_WORDS.has(token)) continue
    const clean = token.replace(NON_ALPHA, '')
    if (clean.length < 4) continue
    counts.set(clean, (counts.get(clean) ?? 0) + 1)
  }

  const top = [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([term]) => term)

  return top.join(' | ')
}
